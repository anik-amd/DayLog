                storePassword = providers.environmentVariable("DAYLOG_STORE_PASSWORD").orNull
                keyAlias = providers.environmentVariable("DAYLOG_KEY_ALIAS").orNull
                keyPassword = providers.environmentVariable("DAYLOG_KEY_PASSWORD").orNull
            }
